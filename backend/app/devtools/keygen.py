"""``python -m app.devtools.keygen --out-dir DIR``

Writes:
  vault_public_keys.json   {kid: base64 raw X25519 public key}   -> API (APP_VAULT_PUBLIC_KEYS_FILE)
  vault_private_keys.json  {kid: base64 raw X25519 private key}  -> delivery ONLY (chmod 600)
  secrets.env              APP_VAULT_ACTIVE_KID, APP_VAULT_FINGERPRINT_KEY, APP_QUOTE_HMAC_KEY,
                           APP_INTERNAL_TOKEN (chmod 600)
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import secrets
import sys
from datetime import datetime, timezone
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from cryptography.hazmat.primitives.serialization import (
    Encoding,
    NoEncryption,
    PrivateFormat,
    PublicFormat,
)


def _b64(raw: bytes) -> str:
    return base64.b64encode(raw).decode()


def _write(path: Path, content: str, mode: int, force: bool) -> None:
    flags = os.O_WRONLY | os.O_CREAT | (os.O_TRUNC if force else os.O_EXCL)
    fd = os.open(path, flags, mode)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.chmod(path, mode)


def generate(out_dir: Path, *, force: bool = False) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    kid = "k" + datetime.now(timezone.utc).strftime("%Y%m%d") + "-" + secrets.token_hex(2)
    priv = X25519PrivateKey.generate()
    priv_raw = priv.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())
    pub_raw = priv.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    paths = {
        "public": out_dir / "vault_public_keys.json",
        "private": out_dir / "vault_private_keys.json",
        "env": out_dir / "secrets.env",
    }
    _write(paths["public"], json.dumps({kid: _b64(pub_raw)}, indent=2) + "\n", 0o644, force)
    _write(paths["private"], json.dumps({kid: _b64(priv_raw)}, indent=2) + "\n", 0o600, force)
    env = "\n".join(
        [
            "# Generated by app.devtools.keygen. Keep out of git.",
            f"APP_VAULT_ACTIVE_KID={kid}",
            f"APP_VAULT_FINGERPRINT_KEY={_b64(secrets.token_bytes(32))}",
            f"APP_QUOTE_HMAC_KEY={_b64(secrets.token_bytes(32))}",
            f"APP_INTERNAL_TOKEN={secrets.token_urlsafe(32)}",
            "",
        ]
    )
    _write(paths["env"], env, 0o600, force)
    return paths


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate vault keys and app secrets")
    parser.add_argument("--out-dir", required=True, type=Path)
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    args = parser.parse_args(argv)
    try:
        paths = generate(args.out_dir, force=args.force)
    except FileExistsError:
        print("refusing to overwrite existing key files (use --force)", file=sys.stderr)
        return 1
    for name, path in paths.items():
        print(f"wrote {name}: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
